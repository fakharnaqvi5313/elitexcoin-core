        pchMessageStart[0] = 0x45; // 'E'
        pchMessageStart[1] = 0x58; // 'X'
        pchMessageStart[2] = 0x43; // 'C'
        pchMessageStart[3] = 0x01;
        nDefaultPort = 17714;
        m_assumed_blockchain_size = 1;

        genesis = CreateGenesisBlock(1785542400, 1074533027, 0x1e0fffff, 7, 0);
